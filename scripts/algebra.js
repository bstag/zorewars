#!/usr/bin/env node
// The block algebra from the command line (docs/block-algebra.md).
//   node scripts/algebra.js build tree.json --rules 94nop [--length 50] [--out x.red]
//   node scripts/algebra.js random --rules 88 [--seed 1]      a random tree that passes the gate
//   node scripts/algebra.js catalog                           writes docs/block-algebra-catalog.md
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { mulberry32 } from '../src/engine/index.js';
import { recipeSettings } from '../tools/blocks/recipes.js';
import { buildTree, randomTree, leaves, combinators, shape } from '../tools/algebra/index.js';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const [command, ...rest] = process.argv.slice(2);
const flags = {}, args = [];
for (let i = 0; i < rest.length; i++) rest[i].startsWith('--') ? (flags[rest[i].slice(2)] = rest[++i]) : args.push(rest[i]);
const rules = flags.rules ?? '94nop', length = Number(flags.length ?? 50);

function report(built) {
  if (flags.out) fs.writeFileSync(flags.out, built.source);
  else process.stdout.write(built.source);
  console.error(`${built.shape}: ${built.total} instructions, gate ${built.verification.shape} passed${flags.out ? ` -> ${flags.out}` : ''}`);
}

if (command === 'build') {
  const text = args[0] === '-' || !args[0] ? fs.readFileSync(0, 'utf8') : fs.readFileSync(args[0], 'utf8');
  report(buildTree(JSON.parse(text), { rules, length }));
} else if (command === 'random') {
  const settings = recipeSettings(rules, length), random = mulberry32(Number(flags.seed ?? 1));
  for (let i = 0; ; i++) {
    const tree = randomTree(settings, random);
    try { const built = buildTree(tree, { rules, length }); console.error(JSON.stringify(tree)); report(built); break; }
    catch (e) { if (i > 200) throw e; }
  }
} else if (command === 'catalog') {
  const range = (p) => Object.entries(p).map(([k, [lo, hi]]) => `${k} ${lo}–${hi}`).join(', ') || 'none';
  const val = (v) => (typeof v === 'function' ? 'depends on parameters' : v ?? '');
  const caps = (b) => [...(b.needs ?? []).map((c) => `needs ${c}`), ...(typeof b.provides === 'function' ? ['provides bomb cells (depends on parameters)'] : Object.keys(b.provides ?? {}).map((c) => `provides ${c}`))].join('; ');
  const rows = Object.values(leaves).map((b) => `| \`${b.id}\` | ${b.kind} | ${b.purpose} | ${range(b.params)} | ${val(b.processes)}${b.grows ? ', grows' : ''} | ${b.exit} | ${b.dialects === '94' ? "'94 only" : "'88 and '94"} | ${caps(b)} |`);
  const crows = Object.values(combinators).map((c) => `| \`${c.id}\` | ${c.purpose} | ${c.kids[0]}–${c.kids[1]} | ${range(c.params)} |`);
  const text = `# Block algebra catalog\n\nGenerated by \`node scripts/algebra.js catalog\` from \`tools/algebra/\`; don't edit by hand. The design is in [block-algebra.md](block-algebra.md).\n\n## Blocks\n\n| Block | Kind | What it does | Parameters | Processes | Exits | Dialects | Capabilities |\n|---|---|---|---|---|---|---|---|\n${rows.join('\n')}\n\n## Combinators\n\n| Combinator | What it does | Members | Parameters |\n|---|---|---|---|\n${crows.join('\n')}\n`;
  fs.writeFileSync(path.join(ROOT, 'docs', 'block-algebra-catalog.md'), text);
  console.log(`docs/block-algebra-catalog.md: ${rows.length} blocks, ${crows.length} combinators`);
} else {
  console.error('usage: node scripts/algebra.js build <tree.json|-> | random | catalog [--rules 94nop] [--length 50] [--seed 1] [--out x.red]');
  process.exit(2);
}
