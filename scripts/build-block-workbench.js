#!/usr/bin/env node
// Package the shared algebra for the buildless website. The CLI discovers
// blocks from disk; the browser worker gets the same supported files as imports.
import { readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { isLeafFile } from '../tools/algebra/leaf-registry.js';

const algebra = new URL('../tools/algebra/', import.meta.url);
const files = readdirSync(new URL('blocks/', algebra)).filter((file) => isLeafFile(file)).sort();

await build({
  entryPoints: [fileURLToPath(new URL('./block-workbench-worker.js', import.meta.url))],
  outfile: fileURLToPath(new URL('../web/vendor/block-workbench.js', import.meta.url)),
  bundle: true,
  format: 'esm',
  minify: true,
  target: 'es2022',
  banner: { js: '/* Generated by npm run build:workbench. Edit the source modules instead. */' },
  plugins: [{
    name: 'browser-leaves',
    setup(builder) {
      builder.onLoad({ filter: /[\\/]algebra[\\/]leaves\.js$/ }, () => ({
        resolveDir: fileURLToPath(algebra),
        contents: [
          "import { registerLeaves } from './leaf-registry.js';",
          ...files.map((file, i) => `import block${i} from ${JSON.stringify(`./blocks/${file}`)};`),
          `export const leaves = registerLeaves([${files.map((file, i) => `[${JSON.stringify(file)}, block${i}]`).join(', ')}]);`,
          "export { modInverse } from './util.js';",
        ].join('\n'),
      }));
    },
  }],
});
