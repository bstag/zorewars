// Encyclopedia content, independent of fetching and page filters.
import {DEFAULT_SETTINGS} from '../src/engine/index.js';
import {escapeHtml as esc} from './editor-status.js';
// Plane and 3D warriors compile on their own battlefield ("torus:40x20x10").
export function settingsFor(battlefield) {
  if (!battlefield) return {};
  const [x, y, z = 1] = battlefield.replace('torus:', '').split('x').map(Number);
  return { ...DEFAULT_SETTINGS, topology: 'torus', sizeX: x, sizeY: y, sizeZ: z, coreSize: x * y * z };
}
export const fieldOf = (entry) => (!entry.battlefield ? 'Ring' : entry.battlefield.split('x').length > 2 ? '3D' : 'Plane');
const fieldLabel = (entry) => (entry.battlefield ? `${fieldOf(entry)} ${entry.battlefield.replace('torus:', '').replaceAll('x', '×')}` : '');

// Split a source line into code and its trailing comment.
function splitComment(line, language) {
  const marker = language === 'redcode' ? ';' : language === 'python' ? '#' : '//';
  let inStr = null;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (language !== 'redcode') {
      if (inStr) {
        if (c === '\\') { i++; continue; }
        if (c === inStr) inStr = null;
        continue;
      }
      if (c === '"' || c === "'" || c === '`') { inStr = c; continue; }
    }
    if (line.startsWith(marker, i)) return [line.slice(0, i).replace(/\s+$/, ''), line.slice(i + marker.length).trim()];
  }
  return [line.replace(/\s+$/, ''), ''];
}

// Two-column listing: code on the left, its explanation on the right.
// Comment-only lines become section notes spanning both columns.
export function annotated(source, language) {
  const rows = [];
  let note = [];
  const flush = () => {
    if (note.length) rows.push(`<tr class="note"><td colspan="2">${esc(note.join(' '))}</td></tr>`);
    note = [];
  };
  for (const raw of source.replace(/\s+$/, '').split('\n')) {
    const [code, comment] = splitComment(raw, language);
    if (!code.trim()) {
      if (/^(name|author|strategy)\b/i.test(comment)) continue; // shown in the card header
      if (comment) note.push(comment); else flush();
      continue;
    }
    flush();
    rows.push(`<tr><td class="code">${esc(code)}</td><td class="why">${esc(comment)}</td></tr>`);
  }
  flush();
  return `<table class="listing"><tbody>${rows.join('')}</tbody></table>`;
}

function matchups(file, bench, names) {
  const r = bench?.results?.[file];
  if (!r) return '';
  const rows = Object.entries(r.vs)
    .map(([opp, s]) => ({ opp, ...s, pts: (3 * s.w + s.t) / (s.w + s.l + s.t) }))
    .sort((a, b) => b.pts - a.pts);
  const cell = (x) => `<li><span>${esc(names[x.opp] || x.opp)}</span><span class="wlt">${x.w}–${x.l}–${x.t}</span></li>`;
  const rank = bench.ranking.find((x) => x.file === file);
  return `<div class="matchups">
    <div><h5>Best matchups</h5><ul>${rows.slice(0, 3).map(cell).join('')}</ul></div>
    <div><h5>Worst matchups</h5><ul>${rows.slice(-3).reverse().map(cell).join('')}</ul></div>
    <p class="muted small">${rank ? `Ranked #${rank.rank} of ${bench.ranking.length} in the library · ${rank.scorePerRound.toFixed(2)} pts/round · ` : ''}win–loss–tie over ${bench.rounds} rounds per pairing</p>
  </div>`;
}

// Avatar cutouts (web/img/avatars), rendered by the Avatars view at cycle 0 on a
// transparent background: plane/plaid.js -> plane-plaid.webp.
const portraitOf = (file) => `img/avatars/${file.replace(/\.(red|js|py)$/, '').replaceAll('/', '-')}.webp`;

export function card(entry, source, compiled, bench, names, conversions = []) {
  const lang = entry.language;
  const opponent = entry.opponent || 'dwarf.red';
  const text = `${compiled.name} ${entry.family} ${entry.summary} ${entry.how.join(' ')} ${entry.inspiredBy ?? ''}`.replace(/<[^>]+>/g, ' ').toLowerCase();
  return `<article class="wcard" id="${esc(entry.id)}" data-family="${esc(entry.family)}" data-field="${fieldOf(entry)}" data-text="${esc(text)}">
    <header>
      <div>
        <h3>${esc(compiled.name)}</h3>
        <p class="byline"><span class="fam">${esc(entry.family)}</span>${entry.battlefield ? ` · ${esc(fieldLabel(entry))}` : ''}${entry.era ? ` · ${esc(entry.era)}` : ''} · ${compiled.instructions.length} instructions${lang !== 'redcode' ? ` · generated by ${esc(lang === 'javascript' ? 'JavaScript' : 'Python')}` : ''}${
          conversions.length ? ` · also in ${conversions.map((c) => `<a href="../warriors/${esc(c.file)}">${c.dialect === '88' ? "ICWS'88" : c.language === 'python' ? 'Python' : 'JavaScript'}</a>`).join(', ')}` : ''}</p>
      </div>
      <a class="btn" href="index.html?load=${encodeURIComponent(entry.file)},${encodeURIComponent(opponent)}">Watch it fight</a>
    </header>
    <div class="intro">
      <div>
        ${entry.inspiredBy ? `<p class="lineage">${entry.inspiredBy}</p>` : ''}
        <p class="summary">${entry.summary}</p>
      </div>
      <figure class="portrait">
        <img src="${esc(portraitOf(entry.file))}" loading="lazy" alt="${esc(compiled.name)} as an avatar, its body built from its own code">
        <figcaption>Its avatar, built from its code</figcaption>
      </figure>
    </div>
    <div class="cols">
      <div class="how">
        <h4>How it works</h4>
        <ol>${entry.how.map((s) => `<li>${s}</li>`).join('')}</ol>
        <h4>Strengths and weaknesses</h4>
        <ul class="sw-list">${entry.strengths.map((s) => `<li class="plus">${s}</li>`).join('')}${entry.weaknesses.map((s) => `<li class="minus">${s}</li>`).join('')}</ul>
        ${entry.tryIt ? `<div class="exercise"><b>Try it:</b> ${entry.tryIt}</div>` : ''}
      </div>
      <div class="src">
        <h4>Line by line <a class="small" href="../warriors/${esc(entry.file)}">${esc(entry.file)}</a></h4>
        ${annotated(source, lang)}
        ${matchups(entry.file, bench, names)}
      </div>
    </div>
  </article>`;
}

