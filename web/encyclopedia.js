// Renders the warrior encyclopedia from warriors/encyclopedia.json, the
// warrior source files (their comments become the line-by-line breakdown)
// and warriors/benchmarks.json.

import { compile, DEFAULT_SETTINGS } from '../src/engine/index.js';

const $ = (sel) => document.querySelector(sel);
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

// Plane and 3D warriors compile on their own battlefield ("torus:40x20x10").
function settingsFor(battlefield) {
  if (!battlefield) return {};
  const [x, y, z = 1] = battlefield.replace('torus:', '').split('x').map(Number);
  return { ...DEFAULT_SETTINGS, topology: 'torus', sizeX: x, sizeY: y, sizeZ: z, coreSize: x * y * z };
}
const fieldOf = (entry) => (!entry.battlefield ? 'Ring' : entry.battlefield.split('x').length > 2 ? '3D' : 'Plane');
const fieldLabel = (entry) => (entry.battlefield ? `${fieldOf(entry)} ${entry.battlefield.replace('torus:', '').replaceAll('x', '×')}` : '');

async function getJSON(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url}: ${r.status}`);
  return r.json();
}

// Split a source line into code and its trailing comment.
function splitComment(line, language) {
  const marker = language === 'redcode' ? ';' : language === 'python' ? '#' : '//';
  let inStr = null;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (language !== 'redcode') {
      if (inStr) { if (c === inStr && line[i - 1] !== '\\') inStr = null; continue; }
      if (c === '"' || c === "'" || c === '`') { inStr = c; continue; }
    }
    if (line.startsWith(marker, i)) return [line.slice(0, i).replace(/\s+$/, ''), line.slice(i + marker.length).trim()];
  }
  return [line.replace(/\s+$/, ''), ''];
}

// Two-column listing: code on the left, its explanation on the right.
// Comment-only lines become section notes spanning both columns.
function annotated(source, language) {
  const rows = [];
  let note = [];
  const flush = () => {
    if (note.length) rows.push(`<tr class="note"><td colspan="2">${esc(note.join(' '))}</td></tr>`);
    note = [];
  };
  for (const raw of source.replace(/\s+$/, '').split('\n')) {
    const [code, comment] = splitComment(raw, language);
    if (!code.trim()) {
      if (/^(name|author|strategy)\b/i.test(comment)) continue; // shown in the card header
      if (comment) note.push(comment); else flush();
      continue;
    }
    flush();
    rows.push(`<tr><td class="code">${esc(code)}</td><td class="why">${esc(comment)}</td></tr>`);
  }
  flush();
  return `<table class="listing"><tbody>${rows.join('')}</tbody></table>`;
}

function matchups(file, bench, names) {
  const r = bench?.results?.[file];
  if (!r) return '';
  const rows = Object.entries(r.vs)
    .map(([opp, s]) => ({ opp, ...s, pts: (3 * s.w + s.t) / (s.w + s.l + s.t) }))
    .sort((a, b) => b.pts - a.pts);
  const cell = (x) => `<li><span>${esc(names[x.opp] || x.opp)}</span><span class="wlt">${x.w}–${x.l}–${x.t}</span></li>`;
  const rank = bench.ranking.find((x) => x.file === file);
  return `<div class="matchups">
    <div><h5>Best matchups</h5><ul>${rows.slice(0, 3).map(cell).join('')}</ul></div>
    <div><h5>Worst matchups</h5><ul>${rows.slice(-3).reverse().map(cell).join('')}</ul></div>
    <p class="muted small">${rank ? `Ranked #${rank.rank} of ${bench.ranking.length} in the library · ${rank.scorePerRound.toFixed(2)} pts/round · ` : ''}win–loss–tie over ${bench.rounds} rounds per pairing</p>
  </div>`;
}

function card(entry, source, compiled, bench, names, conversions = []) {
  const lang = entry.language;
  const opponent = entry.opponent || 'dwarf.red';
  const text = `${compiled.name} ${entry.family} ${entry.summary} ${entry.how.join(' ')} ${entry.inspiredBy ?? ''}`.replace(/<[^>]+>/g, ' ').toLowerCase();
  return `<article class="wcard" id="${esc(entry.id)}" data-family="${esc(entry.family)}" data-field="${fieldOf(entry)}" data-text="${esc(text)}">
    <header>
      <div>
        <h3>${esc(compiled.name)}</h3>
        <p class="byline"><span class="fam">${esc(entry.family)}</span>${entry.battlefield ? ` · ${esc(fieldLabel(entry))}` : ''}${entry.era ? ` · ${esc(entry.era)}` : ''} · ${compiled.instructions.length} instructions${lang !== 'redcode' ? ` · generated by ${esc(lang === 'javascript' ? 'JavaScript' : 'Python')}` : ''}${
          conversions.length ? ` · also in ${conversions.map((c) => `<a href="../warriors/${esc(c.file)}">${c.language === 'python' ? 'Python' : 'JavaScript'}</a>`).join(' and ')}` : ''}</p>
      </div>
      <a class="btn" href="index.html?load=${encodeURIComponent(entry.file)},${encodeURIComponent(opponent)}">Watch it fight</a>
    </header>
    ${entry.inspiredBy ? `<p class="lineage">${entry.inspiredBy}</p>` : ''}
    <p class="summary">${entry.summary}</p>
    <div class="cols">
      <div class="how">
        <h4>How it works</h4>
        <ol>${entry.how.map((s) => `<li>${s}</li>`).join('')}</ol>
        <h4>Strengths and weaknesses</h4>
        <ul class="sw-list">${entry.strengths.map((s) => `<li class="plus">${s}</li>`).join('')}${entry.weaknesses.map((s) => `<li class="minus">${s}</li>`).join('')}</ul>
        ${entry.tryIt ? `<div class="exercise"><b>Try it:</b> ${entry.tryIt}</div>` : ''}
      </div>
      <div class="src">
        <h4>Line by line <a class="small" href="../warriors/${esc(entry.file)}">${esc(entry.file)}</a></h4>
        ${annotated(source, lang)}
        ${matchups(entry.file, bench, names)}
      </div>
    </div>
  </article>`;
}

async function main() {
  const [data, library, bench] = await Promise.all([
    getJSON('../warriors/encyclopedia.json'),
    getJSON('../warriors/index.json'),
    getJSON('../warriors/benchmarks.json').catch(() => null),
  ]);
  const names = Object.fromEntries(library.map((e) => [e.file, e.name]));

  // Filters: battlefield and family chips, and a search over each card's text.
  const filter = { family: 'All', field: 'All' };
  const chips = (el, values, key) => {
    el.innerHTML = ['All', ...values].map((f) => `<button class="chip" aria-pressed="${f === filter[key]}" data-f="${esc(f)}">${esc(f === 'All' ? (key === 'field' ? 'All battlefields' : 'All families') : f)}</button>`).join('');
  };
  const families = [...new Set(data.warriors.map((w) => w.family))].sort();
  const fields = ['Ring', 'Plane', '3D'].filter((f) => data.warriors.some((w) => fieldOf(w) === f));
  const applyFilter = () => {
    const words = $('#encSearch').value.trim().toLowerCase().split(/\s+/).filter(Boolean);
    let n = 0;
    for (const c of document.querySelectorAll('.wcard')) {
      c.hidden = !((filter.family === 'All' || c.dataset.family === filter.family)
        && (filter.field === 'All' || c.dataset.field === filter.field)
        && words.every((w) => c.dataset.text.includes(w)));
      if (!c.hidden) n++;
    }
    $('#encCount').textContent = `${n} of ${data.warriors.length} warriors`;
  };
  for (const [el, values, key] of [[$('#filters'), families, 'family'], [$('#fieldFilters'), fields, 'field']]) {
    chips(el, values, key);
    el.addEventListener('click', (e) => {
      const b = e.target.closest('.chip');
      if (!b) return;
      filter[key] = b.dataset.f;
      chips(el, values, key);
      applyFilter();
    });
  }
  $('#encSearch').addEventListener('input', applyFilter);

  // Ranking table.
  if (bench) {
    $('#ranking').innerHTML = `<table class="ref"><thead><tr><th>#</th><th>Warrior</th><th>Family</th><th>Pts/round</th></tr></thead><tbody>${
      bench.ranking.map((r) => {
        const entry = data.warriors.find((w) => w.file === r.file);
        const fam = entry?.family || library.find((l) => l.file === r.file)?.category || '';
        return `<tr><td>${r.rank}</td><td>${entry ? `<a href="#${esc(entry.id)}">${esc(names[r.file] || r.file)}</a>` : esc(names[r.file] || r.file)}</td><td>${esc(fam)}</td><td>${r.scorePerRound.toFixed(2)}</td></tr>`;
      }).join('')}</tbody></table>
      <p class="muted small">Round robin, ${bench.rounds} rounds per pairing, seed ${bench.seed}, generated ${esc(bench.generated)}. Regenerate with <code>node scripts/benchmark.js</code>.</p>`;
  }

  // Hall of fame: historical warriors, linked to their originals.
  const byId = Object.fromEntries(data.warriors.map((w) => [w.id, w]));
  // "Fight" imports the original into the arena against our version of the idea.
  const fight = (h) => `index.html?url=${encodeURIComponent(h.url)}&vs=${encodeURIComponent(byId[h.ours]?.file || 'dwarf.red')}`;
  $('#hof').innerHTML = `<table class="ref"><thead><tr><th>Year</th><th>Warrior</th><th>Author</th><th>Family</th><th>Why it matters</th><th>Ours</th><th></th></tr></thead><tbody>${
    data.hallOfFame.map((h) => `<tr><td class="yr">${esc(h.year)}</td><td><a href="${esc(h.url)}">${esc(h.name)}</a></td><td>${esc(h.author)}</td><td>${esc(h.family)}</td><td>${esc(h.note)}</td><td>${
      h.ours && byId[h.ours] ? `<a href="#${esc(h.ours)}">${esc(byId[h.ours].name)}</a>` : ''}</td><td><a class="btn fight" href="${fight(h)}" title="Load the original into the arena">Fight</a></td></tr>`).join('')
  }</tbody></table>`;

  // Warrior cards.
  const cards = await Promise.all(data.warriors.map(async (entry) => {
    const source = await fetch(`../warriors/${entry.file}`).then((r) => r.text());
    const compiled = entry.language === 'python' ? { name: entry.name, instructions: [] } : compile(source, entry.language, settingsFor(entry.battlefield));
    const conversions = library.filter((e) => e.convertedFrom === entry.file);
    return card(entry, source, compiled, bench, names, conversions);
  }));
  $('#cards').innerHTML = cards.join('');
  applyFilter();
  $('#toc-warriors').innerHTML = data.warriors.map((w) => `<a href="#${esc(w.id)}">${esc(w.name)}</a>`).join('');
  if (location.hash) document.querySelector(location.hash)?.scrollIntoView();
}

main().catch((e) => {
  $('#cards').innerHTML = `<p class="bad">Could not load the encyclopedia: ${esc(e.message)}. Serve the project with <code>npm start</code>.</p>`;
});
