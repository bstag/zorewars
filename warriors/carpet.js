// Carpet Bomber: a bomber whose inner loop is unrolled by a JavaScript loop.
// Each pass drops a "carpet" of N bombs in a row, then jumps ahead GAP cells.
// The JavaScript also does the maths to guarantee the carpets never land on
// the warrior's own code.
name("Carpet Bomber");
author("ZoreWars");
strategy("Drops N bombs in a row, then skips GAP cells. Generated by a JS loop.");

const N = 4;            // bombs per carpet (one unrolled MOV each)
const GAP = 16;         // distance between carpets; must divide CORESIZE
const LENGTH = N + 4;   // ptr + N MOVs + ADD + JMP + bomb

// Carpets cover offsets LENGTH..LENGTH+N-1 (mod GAP); our code is 0..LENGTH-1.
if (CORESIZE % GAP !== 0 || LENGTH + N > GAP) {
  throw new Error("choose GAP so that carpets miss our own code");
}

org("loop");
label("ptr");  dat.f(imm(0), imm(LENGTH));
label("loop");
for (let i = 0; i < N; i++) mov.i("bomb", postinc("ptr"));
add.ab(imm(GAP - N), "ptr");
jmp("loop");
label("bomb"); dat.f(imm(0), imm(0));
